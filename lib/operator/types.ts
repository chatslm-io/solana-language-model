import type { JournalEntry } from "@/lib/chain/batch";
import type { Network } from "./config";
import type { RpcPolicy } from "@/lib/chain/rpc-policy";
import type { PublicProgramJob } from "./program-types";
export type RpcSettings = Partial<Record<Network, RpcPolicy>>;
export type RpcInfo = RpcPolicy & { endpoint: string; paidAvailable: boolean };
export type Mode = "test" | "upload" | "withdraw";
export type PreparedModel = {
  id: string;
  manifest: import("@/lib/model/manifest").Manifest;
};
export type Job = {
  id: string;
  cluster: Network;
  mode: Mode;
  rpcPolicy?: RpcPolicy;
  owner: string;
  program: string;
  phase: "preparing" | "ready" | "running" | "paused" | "complete" | "failed";
  message: string;
  created: number;
  quotedAt?: number;
  deployment?: string;
  manifestId?: string;
  accounts: string[];
  bytes: number;
  tensors: number;
  uploadTotals?: { shards: number; transactions: number };
  file?: string;
  source?: { repo: string; revision: string; file: string };
  expectedRefund: string;
  deposit: string;
  estimatedFees: string;
  feeBudget: string;
  transactionBudget: number;
  reservedDeposit: string;
  reservedFees: string;
  signedTransactions: number;
  reclaimed: string;
  verifiedBytes: number;
  journal: JournalEntry[];
  approved: boolean;
  stage: "upload" | "withdraw";
  downloadBytes?: number;
  downloadTotal?: number;
};
export type OperationProgress = {
  percent: number;
  shards?: { completed: number; total: number; remaining: number };
  accounts?: { completed: number; total: number; remaining: number };
  transactions: { completed: number; total: number; remaining: number };
};
export type PublicJob = Omit<Job, "journal"> & {
  lastSignature?: string;
  operationProgress?: OperationProgress;
};
export type OperatorStatus = {
  cluster: Network;
  owner: string | null;
  program: string | null;
  balance: string;
  refundable: string;
  accounts: number;
  maxDeposit: string;
  maxFees: string;
  busy: boolean;
  rpc: RpcInfo;
  programDeployment?: PublicProgramJob | null;
  job: PublicJob | null;
  error?: string;
};
