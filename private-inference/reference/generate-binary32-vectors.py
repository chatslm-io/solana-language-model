"""Generate public synthetic binary32 vectors independently of the TS compiler.
Python struct rounds exact binary64 sums/products of binary32 inputs back to
binary32. NaNs use the primitive's explicit canonical quiet payload policy.
No model, key, ciphertext, or conversation input is read.
"""
import json
import math
import struct


def value(bits):
    return struct.unpack('<f', struct.pack('<I', bits))[0]


def bits(number):
    if math.isnan(number):
        return '7fc00000'
    try:
        return struct.pack('<f', number)[::-1].hex()
    except OverflowError:
        return 'ff800000' if number < 0 else '7f800000'


pairs = [
    (0, 0x80000000), (0x80000000, 0x80000000), (1, 1),
    (0x007fffff, 1), (0x00800000, 0x807fffff),
    (0x3f800000, 0x33800000), (0x3f800001, 0x33800000),
    (0x3f800000, 0xbf800000), (0x3f800001, 0xbf800000),
    (0x7f7fffff, 0x7f7fffff), (0xff7fffff, 0xff7fffff),
    (0x7f800000, 0xff800000), (0x7fc00001, 0x3f800000),
    (0x7f800001, 0x3f800000), (0xff800000, 0x3f800000),
    (0x00800000, 0x3f000000), (1, 0x3f000000),
    (3, 0x3f000000), (0x007fffff, 0x3f800001),
    (0x00800000, 0x00800000), (0x7f800000, 0),
    (0x3f800001, 0x3f7fffff), (0xbf800000, 0),
    (0xff7fffff, 0x3f800001),
]
print(json.dumps({
    'version': 1,
    'provenance': 'Python3 struct binary32; canonical quiet NaN; generated by reference/generate-binary32-vectors.py',
    'vectors': [{'a': f'{a:08x}', 'b': f'{b:08x}',
                 'add': bits(value(a) + value(b)),
                 'multiply': bits(value(a) * value(b))} for a, b in pairs]
}, indent=2))
